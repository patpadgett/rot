def _authors(total: int, people: list[tuple[str, str, float]]) -> list[AuthorShare]:
    if not people or total <= 0:
        return []
    counts: list[int] = []
    for _, _, share in people:
        counts.append(max(1, int(round(total * share))))
    delta = total - sum(counts)
    counts[0] += delta
    if counts[0] <= 0:
        counts[0] = 1
        counts[-1] -= 1
    result = [
        AuthorShare(name=name, email=email, commits=count)
        for (name, email, _), count in zip(people, counts)
        if count > 0
    ]
    result.sort(key=lambda author: author.commits, reverse=True)
    return result


def _activity(pattern: list[int]) -> list[int]:
    return (pattern + [0] * 12)[:12]


